CREATE TABLE IF NOT EXISTS `uss-ca`.`data_quality_rule` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(32) NOT NULL,
    source_family VARCHAR(32) NOT NULL DEFAULT 'PURE',
    entity_type VARCHAR(64) NOT NULL,
    field_name VARCHAR(128) NULL,
    name VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    rule_text TEXT NOT NULL,
    alert_text TEXT NULL,
    bulk_procedure TEXT NULL,
    category VARCHAR(64) NOT NULL,
    correction_mode VARCHAR(32) NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_dq_rule_code (code),
    KEY idx_dq_rule_family (source_family, enabled),
    KEY idx_dq_rule_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `uss-ca`.`data_quality_execution` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    status VARCHAR(32) NOT NULL,
    trigger_type VARCHAR(32) NOT NULL,
    scope VARCHAR(32) NOT NULL DEFAULT 'FULL',
    entity_type VARCHAR(64) NULL,
    local_record_id BIGINT UNSIGNED NULL,
    sync_execution_id BIGINT UNSIGNED NULL,
    started_at DATETIME(6) NOT NULL,
    finished_at DATETIME(6) NULL,
    total_records INT NOT NULL DEFAULT 0,
    evaluated_records INT NOT NULL DEFAULT 0,
    finding_count INT NOT NULL DEFAULT 0,
    resolved_count INT NOT NULL DEFAULT 0,
    error_count INT NOT NULL DEFAULT 0,
    started_by VARCHAR(128) NULL,
    error_code VARCHAR(100) NULL,
    error_message VARCHAR(1000) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_dq_exec_status (status, started_at),
    KEY idx_dq_exec_trigger (trigger_type, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `uss-ca`.`data_quality_finding` (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    rule_id BIGINT UNSIGNED NOT NULL,
    execution_id BIGINT UNSIGNED NOT NULL,
    finding_key VARCHAR(191) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    local_record_id BIGINT UNSIGNED NOT NULL,
    pure_id BIGINT NULL,
    record_uuid VARCHAR(36) NULL,
    field_name VARCHAR(128) NULL,
    issue_kind VARCHAR(64) NOT NULL,
    correction_mode VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    current_value TEXT NULL,
    suggested_value TEXT NULL,
    evidence_json JSON NULL,
    first_detected_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_detected_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_seen_execution_id BIGINT UNSIGNED NULL,
    resolved_at DATETIME(6) NULL,
    resolved_by VARCHAR(128) NULL,
    resolution_note VARCHAR(1000) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_dq_finding_key (finding_key),
    KEY idx_dq_finding_status (status, last_detected_at),
    KEY idx_dq_finding_rule (rule_id, status),
    KEY idx_dq_finding_entity (entity_type, local_record_id, status),
    KEY idx_dq_finding_execution (execution_id),
    CONSTRAINT fk_dq_finding_rule
        FOREIGN KEY (rule_id) REFERENCES `uss-ca`.`data_quality_rule` (id),
    CONSTRAINT fk_dq_finding_execution
        FOREIGN KEY (execution_id) REFERENCES `uss-ca`.`data_quality_execution` (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

