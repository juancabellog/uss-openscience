function set(tree, path, value) {
  const parts = path.split('.');
  let node = tree;
  for (let i = 0; i < parts.length - 1; i += 1) {
    node[parts[i]] ??= {};
    node = node[parts[i]];
  }
  node[parts[parts.length - 1]] = value;
}

function pair(esTree, enTree, path, spanish, english) {
  set(esTree, path, spanish);
  set(enTree, path, english);
}

